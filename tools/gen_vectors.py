"""
Reference model for the Volcano Monitoring System + generator for the
Logisim test-vector file.

The same thresholds drive three things:
  * the Logisim circuit  (circuit/volcano_monitor.circ)
  * the assembly program (asm/thresholds.inc)
  * this reference model, which produces the test vectors
"""
import os

# key, pin label, value net, watch net, danger net, WATCH, DANGER
SENSORS = [
    ("VIB", "VIB", "SVIB", "WVIB", "DVIB", 40, 70),
    ("TMP", "TMP", "STMP", "WTMP", "DTMP", 60, 85),
    ("GAS", "GAS", "SGAS", "WGAS", "DGAS", 100, 180),
    ("ACT", "ACT", "SACT", "WACT", "DACT", 50, 80),
]

EMERGENCY_AT = 2  # two or more sensors in DANGER raises the alarm


def classify(values):
    """Return (watch, danger, emergency, danger_count) for one sample."""
    watch = any(v >= s[5] for v, s in zip(values, SENSORS))
    danger_bits = [v >= s[6] for v, s in zip(values, SENSORS)]
    danger = any(danger_bits)
    count = sum(danger_bits)
    emergency = count >= EMERGENCY_AT
    return int(watch), int(danger), int(emergency), count


# (VIB, TMP, GAS, ACT) sample values
CASES = [
    (10, 30, 20, 10),    # everything quiet
    (45, 30, 20, 10),    # vibration above WATCH
    (75, 30, 20, 10),    # vibration above DANGER
    (45, 65, 20, 10),    # two sensors on WATCH
    (75, 30, 190, 10),   # two sensors on DANGER -> emergency
    (75, 65, 20, 10),    # one DANGER + one WATCH
    (75, 30, 190, 80),   # three sensors on DANGER
    (39, 59, 99, 49),    # one below every threshold
    (40, 60, 100, 50),   # exactly on every WATCH threshold
    (70, 85, 180, 80),   # exactly on every DANGER threshold
    (69, 84, 179, 79),   # one below every DANGER threshold
    (50, 60, 100, 80),   # mixed thresholds
    (0, 0, 0, 0),        # all zero
    (255, 255, 255, 255),  # saturation
    (40, 84, 179, 49),   # mixed boundaries
    (70, 59, 99, 79),    # mixed boundaries
    (12, 45, 120, 30),   # quiet-ish
    (95, 95, 200, 95),   # everything extreme
]


def build_vector_file(path):
    header = "VIB[8] TMP[8] GAS[8] ACT[8] OUT_WATCH OUT_DANGER OUT_EMERG OUT_DCNT[4]"
    rows = []
    for values in CASES:
        watch, danger, emerg, count = classify(values)
        rows.append(
            " ".join(f"0x{v:02x}" for v in values)
            + f" {watch} {danger} {emerg} 0x{count:x}"
        )
    with open(path, "w") as fh:
        fh.write("# Volcano Monitoring System - Logisim test vectors\n")
        fh.write("# Generated by tools/gen_vectors.py - do not edit by hand.\n")
        fh.write("#\n")
        fh.write("# Inputs  : VIB TMP GAS ACT   (8 bit, 0-255)\n")
        fh.write("# Outputs : OUT_WATCH OUT_DANGER OUT_EMERG (1 bit), OUT_DCNT[4]\n")
        fh.write("#\n")
        fh.write("# Thresholds (shared with asm/thresholds.inc):\n")
        for key, _l, _v, _w, _d, watch, danger in SENSORS:
            fh.write(f"#   {key:<4} WATCH>={watch:<4} DANGER>={danger}\n")
        fh.write("#\n")
        fh.write(header + "\n")
        fh.write("\n".join(rows) + "\n")
    return len(rows)


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


if __name__ == "__main__":
    n = build_vector_file(os.path.join(ROOT, "circuit/volcano_monitor_vectors.txt"))
    print(f"wrote {n} test vectors")
    for values in CASES:
        print(" ", values, "->", classify(values))
